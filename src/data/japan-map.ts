// 5 年の「地図で見る」単元で、日本地図に印を付けて出す場所。
// 日本地図の絵 (都道府県のパス) は data/figures/japan-paths.ts にある (大きいので、図をはじめて出すときに読みこむ)。

/** 経度・緯度 */
export type LonLat = readonly [number, number];

/** 経度・緯度を、日本地図の座標にする (経度 122 度・北緯 47 度が原点。1 度 = 20 単位で、経度は北緯 36 度の長さに合わせる) */
export function lonLatToXY([lon, lat]: LonLat): [number, number] {
  return [(lon - 122) * 20 * Math.cos((36 * Math.PI) / 180), (47 - lat) * 20];
}

/**
 * 地図のどこを見せるか (SVG の viewBox)。
 * main: 北海道から九州まで。sea: 沖縄とまわりの海まで。wide: 東西南北のはしの島までふくめた全体
 */
export const MAP_VIEWS = {
  main: [92, 22, 304, 320],
  sea: [20, 0, 460, 470],
  wide: [0, 0, 545, 545],
} as const;
export type MapView = keyof typeof MAP_VIEWS;

/**
 * 印の形。
 * dot: 点 (湖・半島・島・都市)。area: 大きな丸 (平野・盆地・工業地帯)。
 * line: 線 (山脈・川)。arrow: 矢印 (海流。at の向きに流れる)
 */
export interface Marker {
  shape: 'dot' | 'area' | 'line' | 'arrow';
  at: readonly LonLat[];
  /** area の大きさ (地図の単位)。書かなければ 9 */
  r?: number;
}

export interface Place {
  /** river-ishikari など */
  id: string;
  /** 名前。ふりがなは「漢字(かんじ)」と書く */
  name: string;
  group: PlaceGroup;
  view: MapView;
  marker: Marker;
  explain: string;
}

export type PlaceGroup = '山地・山脈' | '平野' | '盆地' | '川' | '湖' | '半島' | '島' | '海' | '海流' | '工業地帯・地域' | '工業都市' | '雨温図の都市';

const dot = (lon: number, lat: number): Marker => ({ shape: 'dot', at: [[lon, lat]] });
const area = (lon: number, lat: number, r?: number): Marker => ({ shape: 'area', at: [[lon, lat]], r });
const line = (...at: LonLat[]): Marker => ({ shape: 'line', at });
const arrow = (...at: LonLat[]): Marker => ({ shape: 'arrow', at });

type Row = [id: string, name: string, marker: Marker, explain: string, view?: MapView];

/** 場所の id は「なかまの記号-名前」(川と平野など、なかまがちがえば同じ名前がある) */
const rows = (prefix: string, group: PlaceGroup, list: Row[]): Place[] =>
  list.map(([id, name, marker, explain, view = 'main']) => ({ id: `${prefix}-${id}`, name, group, view, marker, explain }));

